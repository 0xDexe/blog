// ---------- Router ----------

function route() {
    let hash = location.hash.replace(/^#/, '');
    try { hash = decodeURIComponent(hash); } catch { /* keep raw */ }

    const article = hash.match(/^(post|project)\/([\w-]+)$/);
    if (article) {
        openArticle(article[1] === 'post' ? 'post' : 'project', article[2]);
        return;
    }

    const wasArticle = closeArticle();

    const tag = hash.match(/^tag\/(.+)$/);
    if (tag) {
        openPanel('tag', tagKey(tag[1]));
        return;
    }
    if (PANELS.includes(hash)) {
        openPanel(hash);
        return;
    }

    closePanel();
    if (hash === 'blog') {
        $('blog').scrollIntoView({ block: 'start' });
    } else if (wasArticle) {
        window.scrollTo(0, homeScrollY);
    } else if (hash === 'home' || hash === '') {
        if (window.scrollY > $('panel').offsetTop) window.scrollTo(0, 0);
    }
}

