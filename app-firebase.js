const $ = id => document.getElementById(id);

function escapeHtml(value) {
    return String(value ?? '')
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#39;');
}

function safeUrl(url) {
    if (!url) return '';
    const trimmed = String(url).trim();
    if (/^https?:\/\//i.test(trimmed) || /^[\w./-]+$/.test(trimmed)) return trimmed;
    return '';
}

function tagKey(label) {
    return String(label).trim().toLowerCase();
}

function tagHref(label) {
    return '#tag/' + encodeURIComponent(tagKey(label));
}

async function fetchText(path) {
    const response = await fetch(path, { cache: 'no-cache' });
    if (!response.ok) throw new Error(`${path} returned HTTP ${response.status}`);
    return response.text();
}

async function fetchJson(path) {
    return JSON.parse(await fetchText(path));
}

function stripQuotes(value) {
    const m = value.match(/^(['"])(.*)\1$/);
    return m ? m[2] : value;
}

// Parse YAML-ish frontmatter. Handles CRLF line endings.
function parseFrontmatter(markdown) {
    const text = markdown.replace(/\r\n?/g, '\n');
    const match = text.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
    if (!match) return { frontmatter: {}, content: text };
    const frontmatter = {};
    match[1].split('\n').forEach(line => {
        const idx = line.indexOf(':');
        if (idx === -1) return;
        const key = line.slice(0, idx).trim();
        const value = line.slice(idx + 1).trim();
        if (!key) return;
        if (value.startsWith('[') && value.endsWith(']')) {
            frontmatter[key] = value.slice(1, -1).split(',').map(v => stripQuotes(v.trim())).filter(Boolean);
        } else {
            frontmatter[key] = stripQuotes(value);
        }
    });
    return { frontmatter, content: match[2] };
}

function tagsHtml(tags, { active } = {}) {
    if (!Array.isArray(tags) || !tags.length) return '';
    return tags.map(t => {
        const isActive = active && tagKey(t) === active;
        return `<a href="${tagHref(t)}" class="tag${isActive ? ' active' : ''}">#${escapeHtml(t)}</a>`;
    }).join('');
}

function formatCount(count) {
    return count === null || count === undefined ? '–' : String(count);
}

