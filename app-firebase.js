const term = { lines: [], history: [], historyPos: -1 };

function termPrint(text, cls = '') {
    term.lines.push({ text, cls });
    if (term.lines.length > 12) term.lines.shift();
    $('term-lines').innerHTML = term.lines
        .map(l => `<div class="term-line ${l.cls}">${escapeHtml(l.text)}</div>`).join('');
    const body = $('term-body');
    body.scrollTop = body.scrollHeight;
}

function findTagKey(name) {
    const key = tagKey(name.replace(/^#/, ''));
    if (tagIndex.has(key)) return key;
    // forgiving match: "ci-cd" or "cicd" -> "ci/cd"
    const loose = s => s.replace(/[^a-z0-9]/g, '');
    for (const k of tagIndex.keys()) if (loose(k) === loose(key)) return k;
    return null;
}

function go(hash) {
    if (location.hash === '#' + hash) route();
    else location.hash = hash;
}

function runCommand(raw) {
    const line = String(raw || '').trim();
    if (!line) return;
    term.history.push(line);
    term.historyPos = term.history.length;
    termPrint('$ ' + line, 'cmd');

    const [cmdRaw, ...rest] = line.split(/\s+/);
    const cmd = cmdRaw.toLowerCase();
    const arg = rest.join(' ').trim();
    const argLower = arg.toLowerCase();

    switch (cmd) {
        case 'help':
            termPrint('whoami · experience · projects · toolbox · tags · tag <name>');
            termPrint('ls blog · cat <post> · contact · clear · exit');
            return;
        case 'whoami': case 'about':
            termPrint('→ opened ~/about'); go('about'); return;
        case 'experience': case 'work': case 'resume':
            termPrint('→ opened ~/experience'); go('experience'); return;
        case 'git':
            if (/^log/.test(argLower)) { termPrint('→ opened ~/experience'); go('experience'); }
            else termPrint('only `git log` works here.', 'err');
            return;
        case 'projects':
            termPrint('→ opened ~/projects'); go('projects'); return;
        case 'toolbox': case 'skills': case 'stack':
            termPrint('→ opened ~/toolbox'); go('toolbox'); return;
        case 'tags':
            termPrint('→ opened ~/tags'); go('tags'); return;
        case 'tag': {
            if (!arg) { termPrint('usage: tag <name>   e.g. tag vllm'); return; }
            const key = findTagKey(arg);
            if (!key) { termPrint(`nothing tagged "${arg}". try: tags`, 'err'); return; }
            termPrint(`→ indexed #${tagIndex.get(key).label}`);
            go('tag/' + encodeURIComponent(key));
            return;
        }
        case 'ls':
            if (/^blog/.test(argLower)) {
                blogPosts.forEach(p => termPrint(`${p.slug}.md`));
                if (blogPosts.length) termPrint('open one with: cat <name>');
            } else if (/^proj/.test(argLower)) {
                projects.forEach(p => termPrint(`${p.slug}.md`));
            } else {
                termPrint('about/  blog/  projects/  experience/  toolbox/  tags/');
            }
            return;
        case 'cat': case 'open': case 'less': case 'vim': {
            if (!arg) { termPrint(`usage: ${cmd} <post or project>   (see: ls blog)`); return; }
            const name = argLower.replace(/\.md$/, '').replace(/^(blog|projects)\//, '');
            const post = blogPosts.find(p => p.slug === name) || blogPosts.find(p => p.slug.includes(name));
            const project = projects.find(p => p.slug === name) || projects.find(p => p.slug.includes(name));
            if (post) { termPrint(`→ opening ${post.slug}.md`); go('post/' + post.slug); }
            else if (project) { termPrint(`→ opening ${project.slug}.md`); go('project/' + project.slug); }
            else termPrint(`${cmd}: ${arg}: no such file. try: ls blog`, 'err');
            return;
        }
        case 'blog':
            termPrint('→ ~/blog is right below ↓'); go('blog'); return;
        case 'contact': case 'email':
            termPrint('→ opened ~/contact'); go('contact'); return;
        case 'clear':
            term.lines = []; $('term-lines').innerHTML = ''; return;
        case 'exit': case 'cd': case 'q': case ':q':
            go('home'); return;
        case 'sudo':
            termPrint('nice try.'); return;
        case 'rm':
            termPrint('let\'s not.'); return;
        default:
            termPrint(`command not found: ${cmdRaw}. try: help`, 'err');
    }
}

function setupTerminal() {
    const input = $('term-input');
    $('term-form').addEventListener('submit', e => {
        e.preventDefault();
        const value = input.value;
        input.value = '';
        runCommand(value);
    });
    input.addEventListener('keydown', e => {
        if (e.key === 'ArrowUp' && term.history.length) {
            e.preventDefault();
            term.historyPos = Math.max(0, term.historyPos - 1);
            input.value = term.history[term.historyPos] || '';
        } else if (e.key === 'ArrowDown' && term.history.length) {
            e.preventDefault();
            term.historyPos = Math.min(term.history.length, term.historyPos + 1);
            input.value = term.history[term.historyPos] || '';
        }
    });
    $('term-body').addEventListener('click', e => {
        if (!e.target.closest('a') && !window.getSelection().toString()) input.focus({ preventScroll: true });
    });

    const chips = ['help', 'whoami', 'experience', 'projects', 'toolbox', 'tags', 'contact'];
    $('term-chips').innerHTML = chips.map(c => `<button type="button" data-cmd="${c}">${c}</button>`).join('');
    $('term-chips').addEventListener('click', e => {
        const b = e.target.closest('button[data-cmd]');
        if (b) runCommand(b.dataset.cmd);
    });

    termPrint('welcome. type help, or click a command below.');
}

// ---------- Article page (blog post or project) ----------

async function openArticle(kind, slug) {
    const list = kind === 'project' ? projects : blogPosts;
    const entry = list.find(p => p.slug === slug);
    if (!entry) {
        location.replace(kind === 'project' ? '#projects' : '#blog');
        return;
    }

    if (!currentArticle) homeScrollY = window.scrollY;
    currentArticle = { kind, slug };

    $('home-view').hidden = true;
    $('article-view').hidden = false;
    $('article-content').innerHTML = '<p class="muted">loading…</p>';
    window.scrollTo(0, 0);

    try {
        const dir = kind === 'project' ? PROJECTS_DIR : BLOG_DIR;
        const { frontmatter, content } = parseFrontmatter(await fetchText(dir + entry.file));
        if (!currentArticle || currentArticle.slug !== slug) return; // navigated away meanwhile

        const title = frontmatter.title || entry.title || 'Untitled';
        const tags = Array.isArray(frontmatter.tags) ? frontmatter.tags : (entry.tags || []);

        $('article-back').href = kind === 'project' ? '#projects' : '#blog';
        $('article-back').textContent = kind === 'project' ? '← cd ../projects' : '← cd ../blog';
        $('article-tags').innerHTML = tagsHtml(tags);
        $('article-title').textContent = title;
        $('article-kind').textContent = kind === 'project' ? 'project' : 'post';
        $('article-date').textContent = frontmatter.date || '';
        const words = content.trim().split(/\s+/).length;
        $('article-reading-time').textContent = `${Math.max(1, Math.ceil(words / 200))} min read`;

        const image = safeUrl(frontmatter.image);
        const img = $('article-image');
        if (image) { img.src = image; img.alt = title; img.hidden = false; }
        else { img.removeAttribute('src'); img.hidden = true; }

        // Markdown comes from files in this repo only. Drop a leading H1 that repeats the title.
        const body = content.replace(/^\s*#\s+.+\n/, '');
        $('article-content').innerHTML = marked.parse(body);

        const likeWrap = $('article-like');
        const likeButton = $('post-like-button');
        if (kind === 'post' || kind === 'blog') {
            likeWrap.hidden = false;
            likeButton.dataset.slug = slug;
            renderLikeState(slug);
            likeCounts[slug] = await getLikeCount(slug);
            renderLikeState(slug);
        } else {
            likeWrap.hidden = true;
            likeButton.dataset.slug = '';
        }

        document.title = `${title} — Amartya Mannava`;
    } catch (error) {
        console.error(`Error opening ${kind} ${slug}:`, error);
        $('article-content').innerHTML = '<p class="muted">couldn\'t load this one. <a href="#home">go home</a>.</p>';
    }
}

